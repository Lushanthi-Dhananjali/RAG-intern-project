from typing import List
from pydantic import BaseModel, Field


class ObjectiveAlignmentDetailDto(BaseModel):
    objective_id: int = Field(
        ...,
        description="Unique identifier or index of the objective"
    )
    objective_text: str = Field(
        default="",
        description="The specific learning objective being evaluated"
    )
    semantic_similarity_score: float = Field(
        default=0.0,
        description="Cosine similarity between objective and curriculum source"
    )
    pedagogical_alignment_score: float = Field(
        default=0.0,
        description="Cognitive depth and Bloom taxonomy alignment score"
    )
    is_aligned: bool = Field(
        default=False,
        description="Whether the objective passes the pedagogical threshold"
    )
    alignment_reasoning: str = Field(
        default="",
        description="Detailed evaluation reasoning generated by the model"
    )


class AlignmentReportDto(BaseModel):
    educational_goal: str = Field(
        default="",
        description="Target educational goal or competence level"
    )
    overall_alignment_score: float = Field(
        default=0.0,
        description="Aggregated alignment score across all objectives"
    )
    passed_alignment_guardrail: bool = Field(
        default=False,
        description="True if the plan satisfies the minimum pedagogical threshold"
    )
    detailed_objectives_alignment: List[ObjectiveAlignmentDetailDto] = Field(
        default_factory=list,
        description="Itemized breakdown of alignment for each objective"
    )